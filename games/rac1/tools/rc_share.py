#!/usr/bin/env python3
"""rc_share.py STAGE LEVEL...

One copy of the code the levels share.

Every level program carries its own copies of the game's common code (the moby
helpers, the camera, the HUD...), at addresses of its own: tools/recomp.py
translates each level from its own bytes, so the same routine is translated
once per level, differing only in its constants (data addresses, return
addresses, the immediates around them) and in the functions it calls (each
level's own copy of them).

This pass, run after every level's translation, compares the translated
functions of all the levels. Functions whose C has the same shape (the same
statements, registers and labels, only some literals and callees differing)
become one shared function, rcs_N(RcCtx *c, const RcsRel *R), compiled once
(STAGE/shared/rcs_NNN.c). Each literal that differs between the copies is read
from R->v[k], each callee that differs is called through R->f[k]; a literal or
callee that is the same in every copy stays in the code. Each level keeps its
function under its own name as a one-line call that passes its own table, so
every copy still does exactly what its own bytes say.

A jr's dispatch (switch on the target address) is keyed by the offset from the
function's start, the start being one more per-level value. Not shared: the
region functions (several entries into one routine), functions under
MIN_SIZE, and copies whose differing literals are register numbers, shifts or
other structure (those are different code).
"""
import collections, glob, hashlib, os, re, sys

FUNC = re.compile(r"^void (rc(\d\d)_\w+)\(RcCtx \*c\)\s*$")
# tokens: identifiers, numbers (with a sign glued on when it is unary), punctuation, spaces
TOK = re.compile(r"""
    (?P<ws>\s+)
  | (?P<num>(?<=[\s(])-?(?:0x[0-9A-Fa-f]+|\d+)(?:ULL|ull|u|U)?\b)
  | (?P<num2>(?:0x[0-9A-Fa-f]+|\d+)(?:ULL|ull|u|U)?\b)
  | (?P<id>[A-Za-z_]\w*)
  | (?P<p>.)""", re.S | re.X)
LABEL = re.compile(r"^L_[0-9A-F]{8}$")


def parse_level(stage, lv):
    """{name: (file, text)} for the multi-line translated functions of a level"""
    out = {}
    for f in sorted(glob.glob(os.path.join(stage, "l" + lv, "rc_funcs_*.c"))):
        cur, buf = None, []
        for line in open(f):
            if cur is None:
                m = FUNC.match(line)
                if m: cur, buf = m.group(1), [line]
                continue
            buf.append(line)
            if line.startswith("}"):
                out[cur] = (f, "".join(buf)); cur = None
    return out


def tokens(text):
    res = []
    for m in TOK.finditer(text):
        k = m.lastgroup
        if k == "ws": continue
        res.append(("num" if k in ("num", "num2") else k, m.group(), m.span()))
    return res


def skeleton(name, lv, toks):
    """the shape: labels by first appearance, level symbols and numbers left out (but a number
    in a structural place, see structural(), stays, and the others keep their C type)"""
    pre = "rc%s_" % lv
    lab = {}
    sk = []
    for i, (k, t, _) in enumerate(toks):
        if k == "num": sk.append(t if structural(toks, i) else "#" + num_ctype(t))
        elif k == "id" and LABEL.match(t): sk.append(lab.setdefault(t, "L%d" % len(lab)))
        elif k == "id" and t.startswith(pre): sk.append("@")
        else: sk.append(t)
    return hashlib.sha1("\x00".join(sk).encode()).hexdigest()


def num_ctype(t):
    if t.lower().endswith("ull"): return "u64"
    if t.lower().startswith(("0x", "-0x")): return "u32"
    return "s32"


def num_value(t):
    s = t.rstrip("uUlL")
    return int(s, 0) & 0xFFFFFFFF


def structural(toks, i):
    """a number whose place makes it structure (an index, a shift count, an array size)"""
    prev = [t for _, t, _ in toks[max(0, i - 2):i]]
    nxt = toks[i + 1][1] if i + 1 < len(toks) else ""
    if prev and prev[-1] in ("[", "<<", ">>", "case"): return True
    if nxt == "]": return True
    if len(prev) == 2 and prev[0] in ("VF", "VI", "ACC") and prev[1] == "(": return True
    return False


MIN_SIZE = 400        # smaller functions: a stub and a table would cost about what they save
HDR = ('/* generated by tools/rc_share.py: the code the levels share, translated once */\n'
       '#include "rc.h"\n'
       'typedef struct RcsRel { const u32 *v; void (*const *f)(RcCtx *); } RcsRel;\n')


def relative_switch(text):
    """a jr's dispatch, `switch (tgt) { case 0xADDR: goto L_ADDR; ... }`, keyed by the offset
    from the function's first instruction (the smallest case: every instruction is a label in
    such a function) instead of by address, so the copies match; None for other switches"""
    if text.count("switch (") != text.count("switch (tgt) {"): return None
    cases = [int(x, 16) for x in re.findall(r"case 0x([0-9A-F]{8}): goto", text)]
    if not cases: return None
    base = min(cases)
    text = text.replace("switch (tgt) {", "switch ((u32)tgt - 0x%08Xu) {" % base)
    return re.sub(r"case 0x([0-9A-F]{8}):", lambda m: "case 0x%X:" % (int(m.group(1), 16) - base), text)


def level_job(args):
    """(worker) a level's functions with the hash of their shape"""
    stage, lv = args
    res = []
    for name, (f, text) in parse_level(stage, lv).items():
        if len(text) < MIN_SIZE: continue
        norm = relative_switch(text) if "switch" in text else text
        if norm is None: continue
        res.append((name, f, text, norm, skeleton(name, lv, tokens(norm))))
    return lv, res


def group_job(args):
    """(worker) one group of copies: the shared function and each copy's entry, or None"""
    gid, mem = args                       # [(lv, name, text)]
    toks = [tokens(t) for _, _, t in mem]
    toks0 = toks[0]
    ntok = len(toks0)
    if any(len(t) != ntok for t in toks): return None
    lv0, name0, text0 = mem[0]
    vp, fp = {}, {}
    for i in range(ntok):
        k = toks0[i][0]
        if k == "id" and LABEL.match(toks0[i][1]): continue
        vals = [t[i][1] for t in toks]
        if k == "id" and vals[0].startswith("rc%s_" % lv0):
            if i == 1: continue          # the function's own name
            # a level symbol: only as a callee, NAME(c)
            if not (i + 3 < ntok and toks0[i + 1][1] == "(" and toks0[i + 2][1] == "c" and toks0[i + 3][1] == ")"): return None
            fp[i] = True; continue
        if len(set(vals)) == 1: continue
        if k != "num" or structural(toks0, i) or len({num_ctype(v) for v in vals}) != 1: return None
        vp[i] = num_ctype(vals[0])
    vidx = {i: k for k, i in enumerate(sorted(vp))}
    fidx = {i: k for k, i in enumerate(sorted(fp))}
    subs, decls = [], set()
    for i, (k, t, sp) in enumerate(toks0):
        if i == 1: subs.append((sp[0], sp[1], "rcs_%d" % gid)); continue
        if i in vidx: subs.append((sp[0], sp[1], "((%s)R->v[%d])" % (vp[i], vidx[i]))); continue
        if i in fidx: subs.append((sp[0], sp[1], "R->f[%d]" % fidx[i])); continue
        if k == "id" and t.startswith("rc%s_" % lv0) and not LABEL.match(t): return None
        if (k == "id" and re.match(r"rc_\w+$", t) and i + 3 < ntok and toks0[i + 1][1] == "(" and toks0[i + 2][1] == "c"
                and toks0[i + 3][1] == ")"):
            decls.add(t)
    body = text0
    for a, b, r in sorted(subs, reverse=True): body = body[:a] + r + body[b:]
    body = body.replace("rcs_%d(RcCtx *c)" % gid, "rcs_%d(RcCtx *c, const RcsRel *R)" % gid, 1)
    body = "".join("void %s(RcCtx *c);\n" % d for d in sorted(decls)) + body
    reps = []
    for (lv, name, _), tk in zip(mem, toks):
        vals = [tk[i][1] for i in sorted(vp)]
        fns = [tk[i][1] for i in sorted(fp)]
        tag = "rcs%d_%s" % (gid, name)
        rep = ["void rcs_%d(RcCtx *c, const RcsRel *R);" % gid]
        if vals: rep.append("static const u32 %s_v[] = {%s};" % (tag, ", ".join("0x%08Xu" % num_value(v) for v in vals)))
        if fns: rep.append("static void (*const %s_f[])(RcCtx *) = {%s};" % (tag, ", ".join(fns)))
        rep.append("static const RcsRel %s = {%s, %s};" % (tag, tag + "_v" if vals else "0", tag + "_f" if fns else "0"))
        rep.append("void %s(RcCtx *c) { rcs_%d(c, &%s); }\n" % (name, gid, tag))
        reps.append((lv, name, "\n".join(rep)))
    return gid, body, reps


def main():
    import multiprocessing
    stage, levels_arg = sys.argv[1], sys.argv[2:]
    with multiprocessing.Pool(max(1, min(os.cpu_count() or 1, 16))) as pool:
        per_level = dict(pool.map(level_job, [(stage, lv) for lv in levels_arg]))
        groups = collections.defaultdict(list)            # shape -> [(lv, name, text)]
        info = {}
        for lv in levels_arg:
            for name, f, text, norm, h in per_level[lv]:
                groups[h].append((lv, name, norm)); info[(lv, name)] = (f, text)
        cand = [mem for mem in groups.values() if len(mem) > 1]
        results = pool.map(group_job, list(enumerate(cand)), chunksize=16)
    results = [r for r in results if r]
    os.makedirs(os.path.join(stage, "shared"), exist_ok=True)
    for old in glob.glob(os.path.join(stage, "shared", "rcs_*.c")): os.remove(old)
    CH = 40
    replace = collections.defaultdict(dict)                # level file -> {function: entry}
    saved = 0
    for k in range(0, len(results), CH):
        with open(os.path.join(stage, "shared", "rcs_%03d.c" % (k // CH)), "w") as f:
            f.write(HDR)
            for gid, body, reps in results[k:k + CH]: f.write(body + "\n")
    for gid, body, reps in results:
        for lv, name, rep in reps:
            replace[info[(lv, name)][0]][name] = rep
            saved += len(info[(lv, name)][1])
        saved -= len(info[(reps[0][0], reps[0][1])][1])
    for path, reps in replace.items():
        txt = open(path).read()
        lv = re.search(r"[/\\]l(\d\d)[/\\]", path).group(1)
        for name, rep in reps.items():
            old = info[(lv, name)][1]
            assert old in txt, (path, name)
            txt = txt.replace(old, rep, 1)
        txt = txt.replace('#include "rc_decls.h"\n', '#include "rc_decls.h"\ntypedef struct RcsRel { const u32 *v; void (*const *f)(RcCtx *); } RcsRel;\n', 1)
        open(path, "w").write(txt)
    tot = sum(len(t) for _, t in info.values())
    print("rc_share: %d shared functions for %d copies in levels %s; %d of %d KB of level code moved to one copy" % (
        len(results), sum(len(r[2]) for r in results), ",".join(levels_arg), saved // 1024, tot // 1024))


if __name__ == "__main__":
    main()
