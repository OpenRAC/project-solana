static GLuint mk_tex(GLenum ifmt, int w, int h, GLenum fmt, GLenum type, int linear)
{
    GLuint t; p_glGenTextures(1, &t);
    p_glActiveTexture(GL_TEXTURE0 + 15);
    p_glBindTexture(GL_TEXTURE_2D, t);
    p_glTexImage2D(GL_TEXTURE_2D, 0, (GLint)ifmt, w, h, 0, fmt, type, 0);
    p_glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, linear ? GL_LINEAR : GL_NEAREST);
    p_glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, linear ? GL_LINEAR : GL_NEAREST);
    p_glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_S, GL_CLAMP_TO_EDGE);
    p_glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_T, GL_CLAMP_TO_EDGE);
    p_glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAX_LEVEL, 0);
    return t;
}
static void bind_unit(int u, GLuint t)
{
    if (u < 9 && gc.tex[u] == t) return;
    p_glActiveTexture(GL_TEXTURE0 + u);
    p_glBindTexture(GL_TEXTURE_2D, t);
    if (u < 9) gc.tex[u] = t;
}

static inline u32 tpage(const tgt_t *t, int col, int row) { return (t->bp / 32 + (u32)row * t->bw + (u32)col) & 511; }

static void download(tgt_t *t, const u16 *pg, int n);
static void fbo_forget(GLuint tex);
static tgt_t *tgt_get(u32 bp, u32 bw, int cls, const tgt_t *keep1, const tgt_t *keep2)
{
    int fr = -1, lru = -1;
    for (int i = 0; i < NTG; i++) {
        tgt_t *t = &tg[i];
        if (!t->used) { if (fr < 0) fr = i; continue; }
        if (t->bp == bp && t->bw == bw && t->cls == (u32)cls) { t->lru = ++lru_clock; return t; }
        if (t != keep1 && t != keep2 && (lru < 0 || t->lru < tg[lru].lru)) lru = i;
    }
    if (fr < 0) {                        /* evict the least recently used: its newer pages go to vram first */
        tgt_t *t = &tg[lru];
        u16 pg[512]; int n = 0;
        for (int p = 0; p < 512; p++) if (owner[p] == lru) pg[n++] = (u16)p;
        if (n) download(t, pg, n);
        fbo_forget(t->tex);
        p_glDeleteTextures(1, &t->tex);
        for (int u = 0; u < 9; u++) if (gc.tex[u] == t->tex) gc.tex[u] = ~0u;
        t->used = 0;
        fr = lru;
    }
    tgt_t *t = &tg[fr];
    memset(t, 0, sizeof *t);
    t->used = 1; t->bp = bp; t->bw = bw; t->cls = (u32)cls; t->w = (int)bw * 64; t->lru = ++lru_clock;
    t->ph = CLS_16(cls) ? 64 : 32;
    t->rows = TGH / t->ph;
    if ((u32)t->rows * bw > 512) t->rows = (int)(512 / bw);
    if (CLS_Z(cls)) t->tex = mk_tex(GL_DEPTH_COMPONENT32F, t->w * sc, TGH * sc, GL_DEPTH_COMPONENT, GL_FLOAT, 0);
    else t->tex = mk_tex(GL_RGBA8, t->w * sc, TGH * sc, GL_RGBA, GL_UNSIGNED_BYTE, 1);
    return t;
}

static GLuint fbo_get(GLuint c, GLuint z)
{
    for (int i = 0; i < nfbc; i++) if (fbc[i].c == c && fbc[i].z == z) return fbc[i].fbo;
    if (nfbc == 48) {   /* full: start over (deleted, or the textures they hold would never be freed) */
        p_glBindFramebuffer(GL_FRAMEBUFFER, 0); gc.fbo = ~0u;
        for (int i = 0; i < nfbc; i++) p_glDeleteFramebuffers(1, &fbc[i].fbo);
        nfbc = 0;
    }
    GLuint f; p_glGenFramebuffers(1, &f);
    p_glBindFramebuffer(GL_FRAMEBUFFER, f);
    p_glFramebufferTexture2D(GL_FRAMEBUFFER, GL_COLOR_ATTACHMENT0, GL_TEXTURE_2D, c, 0);
    p_glFramebufferTexture2D(GL_FRAMEBUFFER, GL_DEPTH_ATTACHMENT, GL_TEXTURE_2D, z, 0);
    gc.fbo = f;
    fbc[nfbc].c = c; fbc[nfbc].z = z; fbc[nfbc].fbo = f; nfbc++;
    return f;
}
static void fbo_forget(GLuint tex)
{
    for (int i = 0; i < nfbc; i++)
        if (fbc[i].c == tex || fbc[i].z == tex) {
            /* deleted with the texture: an FBO that still holds a deleted texture keeps its memory
             * alive, so every evicted target leaked its texture (GPU memory grew over a session) */
            if (gc.fbo == fbc[i].fbo) { p_glBindFramebuffer(GL_FRAMEBUFFER, 0); gc.fbo = ~0u; }
            p_glDeleteFramebuffers(1, &fbc[i].fbo);
            fbc[i] = fbc[--nfbc]; i--;
        }
}
static void bind_fbo(GLuint f) { if (gc.fbo != f) { p_glBindFramebuffer(GL_FRAMEBUFFER, f); gc.fbo = f; } }

/* ---- pages between vram and targets ---- */
static u32 *xbuf; static size_t xbuf_n;
static void *xb(size_t n) { if (n > xbuf_n) { free(xbuf); xbuf = malloc(n); xbuf_n = n; } return xbuf; }

static const char *dl_why = "?";
/* the target's newer copy of these pages into vram */
static void download(tgt_t *t, const u16 *pg, int n)
{
    int ti = (int)(t - tg);
    int c0 = 1 << 30, c1 = -1, r0 = 1 << 30, r1 = -1;
    for (int i = 0; i < n; i++) {
        u32 k = (pg[i] - t->bp / 32) & 511;
        int row = (int)(k / t->bw), col = (int)(k % t->bw);
        if (col < c0) c0 = col;
        if (col > c1) c1 = col;
        if (row < r0) r0 = row;
        if (row > r1) r1 = row;
    }
    if (c1 < 0) return;
    {   /* testing: UYA_GLDLLOG=1 logs every readback and why */
        static int dbg = -1; if (dbg < 0) dbg = getenv("UYA_GLDLLOG") != 0;
        if (dbg) uya_log("download v%u: target %04X/%u cls %u, %d pages from %u (%s)", uya_frame_count(), t->bp, t->bw, t->cls, n, pg[0], dl_why); }
    int x0 = c0 * 64, y0 = r0 * t->ph, w = (c1 - c0 + 1) * 64, h = (r1 - r0 + 1) * t->ph;
    void *buf = xb((size_t)w * h * 4 * sc * sc);
    int z = CLS_Z(t->cls);
    p_glBindFramebuffer(GL_READ_FRAMEBUFFER, z ? rd_fbo_z : rd_fbo);
    p_glFramebufferTexture2D(GL_READ_FRAMEBUFFER, z ? GL_DEPTH_ATTACHMENT : GL_COLOR_ATTACHMENT0, GL_TEXTURE_2D, t->tex, 0);
    p_glPixelStorei(GL_PACK_ALIGNMENT, 4);
    p_glReadPixels(x0 * sc, y0 * sc, w * sc, h * sc, z ? GL_DEPTH_COMPONENT : GL_RGBA, z ? GL_FLOAT : GL_UNSIGNED_BYTE, buf);
    p_glFramebufferTexture2D(GL_READ_FRAMEBUFFER, z ? GL_DEPTH_ATTACHMENT : GL_COLOR_ATTACHMENT0, GL_TEXTURE_2D, 0, 0);
    p_glBindFramebuffer(GL_READ_FRAMEBUFFER, gc.fbo == ~0u ? 0 : gc.fbo);
    st.dl_reads++;
    u16 *v16 = (u16 *)vram;
    for (int i = 0; i < n; i++) {
        u32 k = (pg[i] - t->bp / 32) & 511;
        int row = (int)(k / t->bw), col = (int)(k % t->bw);
        if (owner[pg[i]] == ti) owner[pg[i]] = -1;
        st.dl_pages++;
        for (int yy = 0; yy < t->ph; yy++) {
            u32 y = (u32)(row * t->ph + yy);
            /* (upscaled: the texel at the middle of each pixel's block) */
            const u32 *src = (const u32 *)buf + ((size_t)(y - (u32)y0) * sc + (size_t)(sc / 2)) * (size_t)(w * sc) + (size_t)(col * 64 - x0) * sc + (size_t)(sc / 2);
            const float *fs0 = (const float *)src;
            for (u32 xx = 0; xx < 64; xx++) {
                u32 x = (u32)col * 64 + xx, v = src[xx * sc], a;
                float fz = fs0[xx * sc];
                switch (t->cls) {
                case TC32: vram[A32(t->bp, t->bw, x, y)] = v; break;
                case TC16: case TC16S:
                    v16[A16(t->bp, t->bw, x, y, t->cls == TC16 ? gs_block16 : gs_block16s, 0)] =
                        (u16)(((v >> 3) & 31) | (((v >> 11) & 31) << 5) | (((v >> 19) & 31) << 10) | ((v >> 31) << 15));
                    break;
                case TZ32: { double d = (double)fz * 4294967296.0; vram[A32Z(t->bp, t->bw, x, y)] = d >= 4294967295.0 ? 0xFFFFFFFFu : (u32)(d + 0.5); } break;
                case TZ24: a = A32Z(t->bp, t->bw, x, y); vram[a] = (vram[a] & 0xFF000000u) | ((u32)(fz * 16777216.0f + 0.5f) & 0xFFFFFF); break;
                default: { u32 zz = (u32)(fz * 65536.0f + 0.5f); v16[A16(t->bp, t->bw, x, y, t->cls == TZ16 ? gs_block16 : gs_block16s, 0x18)] = (u16)(zz > 0xFFFF ? 0xFFFF : zz); } break;
                }
            }
        }
    }
}
/* vram into the target's copy of a page */
static void upload_page(tgt_t *t, int col, int row)
{
    u32 *buf = xb((size_t)64 * 64 * 4 * (sc * sc + 1));
    u16 *v16 = (u16 *)vram;
    for (int yy = 0; yy < t->ph; yy++) {
        u32 y = (u32)(row * t->ph + yy);
        u32 *o = buf + yy * 64;
        float *of = (float *)o;
        for (u32 xx = 0; xx < 64; xx++) {
            u32 x = (u32)col * 64 + xx, v;
            switch (t->cls) {
            case TC32: o[xx] = vram[A32(t->bp, t->bw, x, y)]; break;
            case TC16: case TC16S:
                v = v16[A16(t->bp, t->bw, x, y, t->cls == TC16 ? gs_block16 : gs_block16s, 0)];
                o[xx] = ((v & 31) << 3) | (((v >> 5) & 31) << 11) | (((v >> 10) & 31) << 19) | ((v & 0x8000) ? 0x80000000u : 0);
                break;
            case TZ32: of[xx] = (float)((double)vram[A32Z(t->bp, t->bw, x, y)] * (1.0 / 4294967296.0)); break;
            case TZ24: of[xx] = (float)(vram[A32Z(t->bp, t->bw, x, y)] & 0xFFFFFF) * (1.0f / 16777216.0f); break;
            default: of[xx] = (float)v16[A16(t->bp, t->bw, x, y, t->cls == TZ16 ? gs_block16 : gs_block16s, 0x18)] * (1.0f / 65536.0f); break;
            }
        }
    }
    if (sc > 1) {   /* upscaled: each pixel fills its sc x sc block */
        u32 *big = buf + 64 * 64, W = 64 * (u32)sc;
        for (int yy = 0; yy < t->ph; yy++)
            for (int k = 0; k < sc; k++) {
                u32 *o = big + ((size_t)yy * sc + k) * W;
                for (u32 xx = 0; xx < 64; xx++) for (int j = 0; j < sc; j++) o[xx * sc + j] = buf[yy * 64 + xx];
            }
        buf = big;
    }
    p_glActiveTexture(GL_TEXTURE0 + 15);
    p_glBindTexture(GL_TEXTURE_2D, t->tex);
    p_glPixelStorei(GL_UNPACK_ALIGNMENT, 4);
    p_glPixelStorei(GL_UNPACK_ROW_LENGTH, 0);
    if (CLS_Z(t->cls)) p_glTexSubImage2D(GL_TEXTURE_2D, 0, col * 64 * sc, row * t->ph * sc, 64 * sc, t->ph * sc, GL_DEPTH_COMPONENT, GL_FLOAT, buf);
    else p_glTexSubImage2D(GL_TEXTURE_2D, 0, col * 64 * sc, row * t->ph * sc, 64 * sc, t->ph * sc, GL_RGBA, GL_UNSIGNED_BYTE, buf);
    st.ul_pages++;
}

/* downloads pages (any owner) to vram, one read per owner */
static void download_any(const u16 *pg, int n, const u8 *skip)
{
    static u16 lst[NTG][512]; int cnt[NTG] = {0};
    for (int i = 0; i < n; i++) {
        int o = owner[pg[i]];
        if (o < 0 || (skip && skip[i])) continue;
        lst[o][cnt[o]++] = pg[i];
    }
    for (int o = 0; o < NTG; o++) if (cnt[o]) download(&tg[o], lst[o], cnt[o]);
}

/* UYA_GL_STRICT=1: also when a texture reads memory another target owns past
 * what it draws (RAC1's frame copy reads a row of the Z buffer at
 * 6%, distant mip chains point level 0 at the display buffer), sync it through
 * GS memory like the software GS sees it; by default those reads see the last
 * synced contents, which saves a GPU readback (a pipeline stall) or two a frame */
static int strict = -1, no_dl;
static u8 *cover;                          /* pages the batch overwrites whole (no upload needed), or 0 */
/* the target's copy of the pages under a rectangle (pixels, inclusive) made current */
static void ensure_valid(tgt_t *t, int x0, int y0, int x1, int y1)
{
    if (x0 < 0) x0 = 0;
    if (y0 < 0) y0 = 0;
    if (x1 > t->w - 1) x1 = t->w - 1;
    if (y1 > t->rows * t->ph - 1) y1 = t->rows * t->ph - 1;
    if (x0 > x1 || y0 > y1) return;
    int ti = (int)(t - tg);
    u16 pg[512]; int n = 0;
    for (int r = y0 / t->ph; r <= y1 / t->ph; r++)
        for (int c = x0 / 64; c <= x1 / 64; c++) {
            u32 p = tpage(t, c, r);
            if (no_dl && owner[p] >= 0 && owner[p] != ti) continue;   /* (UYA_GL_STRICT) */
            if (cover && cover[p] && !t->valid[p]) { t->valid[p] = 1; continue; }   /* overwritten whole: its old contents do not matter */
            if (!t->valid[p]) { pg[n++] = (u16)p; }
        }
    if (!n) return;
    {   /* other targets' newer copies to vram first */
        u16 o[512]; int m = 0;
        for (int i = 0; i < n; i++) if (owner[pg[i]] >= 0 && owner[pg[i]] != ti) o[m++] = pg[i];
        if (m) { static char why[64]; snprintf(why, sizeof why, "pages for target %04X/%u cls %u", t->bp, t->bw, t->cls); dl_why = why; download_any(o, m, 0); }
    }
    for (int i = 0; i < n; i++) {
        u32 k = (pg[i] - t->bp / 32) & 511;
        upload_page(t, (int)(k % t->bw), (int)(k / t->bw));
        t->valid[pg[i]] = 1;
    }
}
/* a draw wrote the pages under a rectangle */
static void claim(tgt_t *t, int x0, int y0, int x1, int y1)
{
    if (x0 < 0) x0 = 0;
    if (y0 < 0) y0 = 0;
    if (x1 > t->w - 1) x1 = t->w - 1;
    if (y1 > t->rows * t->ph - 1) y1 = t->rows * t->ph - 1;
    int ti = (int)(t - tg);
    for (int r = y0 / t->ph; r <= y1 / t->ph; r++)
        for (int c = x0 / 64; c <= x1 / 64; c++) {
            u32 p = tpage(t, c, r);
            if (owner[p] == ti) continue;
            owner[p] = (signed char)ti;
            for (int i = 0; i < NTG; i++) if (i != ti && tg[i].used) tg[i].valid[p] = 0;
        }
}

/* the vram pages under a rectangle of a buffer; full[i]: the rectangle covers the whole page */
static int rect_pages(u32 psm, u32 bp, u32 bw, u32 x, u32 y, u32 w, u32 h, u16 *out, u8 *full)
{
    u32 pw = 64, ph = 32, ppr = bw ? bw : 1;
    switch (psm) {
    case 0x02: case 0x0A: case 0x32: case 0x3A: ph = 64; break;
    case 0x13: pw = 128; ph = 64; ppr = bw > 1 ? bw / 2 : 1; break;
    case 0x14: pw = 128; ph = 128; ppr = bw > 1 ? bw / 2 : 1; break;
    }
    if (!w || !h) return 0;
    if (x > 2047) x = 2047;
    if (y > 2047) y = 2047;
    if (x + w > 2048) w = 2048 - x;
    if (y + h > 2048) h = 2048 - y;
    static u8 seen[512]; static u32 gen_[512], gen;
    gen++;
    int n = 0;
    for (u32 py = y / ph; py <= (y + h - 1) / ph; py++)
        for (u32 px = x / pw; px <= (x + w - 1) / pw; px++) {
            u32 b0 = bp + (py * ppr + px) * 32;
            int whole = !(b0 & 31) && x <= px * pw && x + w >= (px + 1) * pw && y <= py * ph && y + h >= (py + 1) * ph;
            u32 span = 1;
            if (b0 & 31) {   /* a base inside a page: the last block the rectangle reaches decides whether it goes on into the next page */
                u32 cx0 = x > px * pw ? x - px * pw : 0, cx1 = x + w < (px + 1) * pw ? x + w - px * pw - 1 : pw - 1;
                u32 cy0 = y > py * ph ? y - py * ph : 0, cy1 = y + h < (py + 1) * ph ? y + h - py * ph - 1 : ph - 1, mb = 0;
                int tall = (pw == 64 && ph == 64) || (pw == 128 && ph == 128);   /* 16 and 4-bit: 4 x 8 blocks, else 8 x 4 */
                u32 bwid = tall ? pw / 4 : pw / 8, bhgt = tall ? ph / 8 : ph / 4;
                for (u32 yy = cy0 / bhgt; yy <= cy1 / bhgt; yy++)
                    for (u32 xx = cx0 / bwid; xx <= cx1 / bwid; xx++) {
                        u32 bi = (psm & 0x30) == 0x30 ? 31 : (tall ? (psm == 0x0A ? gs_block16s[yy & 7][xx & 3] : gs_block16[yy & 7][xx & 3]) : gs_block32[yy & 3][xx & 7]);
                        if (bi > mb) mb = bi;
                    }
                span = ((b0 & 31) + mb) >= 32 ? 2 : 1;
            }
            for (u32 k = 0; k < span; k++) {
                u32 p = (b0 / 32 + k) & 511;
                if (gen_[p] == gen) { if (!whole) for (int i = 0; i < n; i++) if (out[i] == p) full[i] = 0; continue; }
                gen_[p] = gen; seen[p] = 1;
                out[n] = (u16)p; full[n] = (u8)whole; n++;
            }
        }
    return n;
}

/* ---- textures from the cache ---- */
static int b_on;
static int gc_apass = -1;
static int getenv_cached_nomerge(void) { static int v = -1; if (v < 0) v = getenv("UYA_GL_NOMERGE") != 0; return v; }
static u32 b_clut[256], b_cluth; static int b_clut_saved;   /* the palette a batch's deferred levels decode with */
static u32 rec_clut[512][256], rec_cluth[512];   /* each record's palette (for its levels decoded late) */
void gs_clut_swap(u32 *pal, u32 *hash);   /* gs.c: exchange clut[] and its hash with these */
static void clut_snap(int r) { u32 t[256], h = 0; gs_clut_swap(t, &h); memcpy(rec_clut[r], t, sizeof t); rec_cluth[r] = h; gs_clut_swap(t, &h); }
static pcmd_t bs;
static int in_flush;
void gsgl_flush(void);
static int rec_tci[REC_MAX][7], rec_mxl[REC_MAX];
/* texture cache slots the open batch refers to (gs.c does not reuse them until it is drawn:
 * a slot taken by another texture made the batch decode the old one again at flush time,
 * with whatever palette was loaded by then: textures in the wrong colours for a frame) */
u32 gsgl_tc_pin[TC_N], gsgl_batch_id = 1;
static void pin_levels(const pcmd_t *S)
{
    if (!S->tme || S->rt) return;
    for (int l = 0; l <= S->mxl && l < 7; l++) { int i = S->lv[l].tci; if (i >= 0 && i < TC_N) gsgl_tc_pin[i] = gsgl_batch_id; }
}
static int batch_uses(int tci)
{
    if (!b_on || !bs.tme || bs.rt) return 0;
    for (int l = 0; l <= bs.mxl && l < 7; l++) if (!(bs.defer & (1 << l)) && bs.lv[l].tci == tci) return 1;
    for (int r = 0; r < nrec; r++) for (int l = 0; l <= rec_mxl[r] && l < 7; l++) if (rec_tci[r][l] == tci) return 1;
    return 0;
}
static int atlas_place(int w, int h, int *ax, int *ay)
{
    static int lim = -1;   /* testing: UYA_ATLAS_LIMIT=n uses only n x n of the atlas (it fills and starts over often) */
    if (lim < 0) { const char *e = getenv("UYA_ATLAS_LIMIT"); lim = e ? atoi(e) : ATLAS; if (lim < 256 || lim > ATLAS) lim = ATLAS; }
    int sh = 8; while (sh < h) sh <<= 1;
    if (w > lim || sh > lim) return 0;
    for (int i = 0; i < nshelf; i++)
        if (shelf[i].h == sh && shelf[i].x + w <= lim) { *ax = shelf[i].x; *ay = shelf[i].y; shelf[i].x += (w + 3) & ~3; return 1; }
    if (nshelf == 1024 || shelf_top + sh > lim) return 0;
    shelf[nshelf].y = shelf_top; shelf[nshelf].h = sh; shelf[nshelf].x = (w + 3) & ~3; nshelf++;
    *ax = 0; *ay = shelf_top; shelf_top += sh;
    return 1;
}
void gsgl_flush(void);
void gsgl_tex_touch(const tlevel_t *l)
{
    int i = l->tci;
    if (i < 0 || i >= TC_N || !l->px) return;
    if (tcser[i] == l->ser && tcgl[i] && tcagen[i] == atlas_gen) return;
    if (!in_flush && batch_uses(i)) gsgl_flush();
    int ax, ay;
    if (tcgl[i] && tcagen[i] == atlas_gen && tcw[i] == l->w && tch[i] == l->h) { ax = tcax[i]; ay = tcay[i]; }
    else if (!atlas_place(l->w, l->h, &ax, &ay)) {
        /* full: start over (what the batch being drawn uses must stay: drawn first) */
        if (!in_flush && b_on) gsgl_flush();
        atlas_gen++; nshelf = 0; shelf_top = 0; st.atlas_resets++;
        if (!atlas_place(l->w, l->h, &ax, &ay)) return;
    }
    p_glActiveTexture(GL_TEXTURE0 + 15);
    p_glBindTexture(GL_TEXTURE_2D, atlas_tex);
    p_glPixelStorei(GL_UNPACK_ALIGNMENT, 4);
    p_glPixelStorei(GL_UNPACK_ROW_LENGTH, 0);
    p_glTexSubImage2D(GL_TEXTURE_2D, 0, ax, ay, l->w, l->h, GL_RGBA_INTEGER, GL_UNSIGNED_BYTE, l->px);
    tcgl[i] = 1; tcax[i] = ax; tcay[i] = ay; tcw[i] = l->w; tch[i] = l->h; tcagen[i] = atlas_gen;
    tcser[i] = l->ser;
    st.tex_ul++;
}
static inline int tc_ready(const tlevel_t *l)
{
    int ci = l->tci;
    return l->px && ci >= 0 && ci < TC_N && tcgl[ci] && tcser[ci] == l->ser && tcagen[ci] == atlas_gen;
}

/* the vram pages a texture level covers (exactly, unlike gs.c's slack) */
static int tex_pages(u32 psm, u32 tbp, u32 tbw, u32 tw, u32 th, u16 *out, u8 *full)
{
    u32 bw = tbw ? tbw : 1;
    switch (psm) {   /* the H formats and 24-bit read the 32-bit layout */
    case 0x1B: case 0x24: case 0x2C: case 0x01: psm = 0; break;
    }
    if (tw > bw * 64 && psm != 0x13 && psm != 0x14) tw = bw * 64;
    return rect_pages(psm, tbp, bw, 0, 0, tw, th, out, full);
}
int gsgl_tex_gpu(u32 psm, u32 tbp, u32 tbw, u32 tw, u32 th)
{
    {   /* quick: no target owns anything in the whole span of pages the buffer can reach */
        u32 bits = (psm == 0x14 || psm == 0x24 || psm == 0x2C) ? 4 : (psm == 0x13 || psm == 0x1B) ? 8 : (psm == 0x02 || psm == 0x0A) ? 16 : 32;
        u32 w = (tbw ? tbw : 1) * 64, np = (w * th * bits / 8 + 8191) / 8192 + 1, p0 = tbp / 32, any = 0;
        if (bits == 4 || bits == 8) np += (w * 2 * th * bits / 8 + 8191) / 8192;   /* (their pages are 128 wide) */
        if (np > 512) np = 512;
        for (u32 i = 0; i <= np && !any; i++) any = owner[(p0 + i) & 511] >= 0;
        if (!any) return 0;
    }
    u16 pg[512]; u8 full[512];
    int n = tex_pages(psm, tbp, tbw, tw, th, pg, full);
    for (int i = 0; i < n; i++) if (owner[pg[i]] >= 0) return 1;
    return 0;
}

/* a texture that is a colour target: read on the GPU */
int gsgl_tex_setup(pcmd_t *p)
{
    u32 tbp = BITS(p->tex0, 0, 14), tbw = BITS(p->tex0, 14, 6), psm = BITS(p->tex0, 20, 6);
    if ((psm != 0x00 && psm != 0x01) || (tbp & 31) || !tbw) return 0;
    if (p->mmin >= 2 && BITS(p->tex1, 2, 3)) {   /* mipmapped: from a target only if the LOD is constant and picks level 0 */
        float k = floorf(p->k * 16.0f + 0.5f) / 16.0f;
        if (!(p->fst || p->lcm) || k > ((p->mmin == 3 || p->mmin == 5) ? 0.0f : 0.49f)) return 0;
    }
    int ti = -1;
    for (int i = 0; i < NTG; i++) if (tg[i].used && tg[i].bp == tbp && tg[i].bw == tbw && tg[i].cls == TC32) { ti = i; break; }
    if (ti < 0) return 0;
    u32 tw = 1u << BITS(p->tex0, 26, 4), th = 1u << BITS(p->tex0, 30, 4);
    u16 pg[512]; u8 full[512];
    int n = tex_pages(0, tbp, tbw, tw, th, pg, full), mine = 0;
    for (int i = 0; i < n; i++) {
        if (owner[pg[i]] == ti) mine = 1;
    }
    if (!mine) return 0;
    p->rt = (u16)(ti + 1);
    return 1;
}

void gsgl_clut_changed(void) {}   /* (each record keeps the palette it was drawn with) */

/* ---- the CPU side's reads and writes ---- */
void gsgl_cpu_read_rect(u32 psm, u32 bp, u32 bw, u32 x, u32 y, u32 w, u32 h)
{
    if (!in_flush) gsgl_flush();
    u16 pg[512]; u8 full[512];
    int n = rect_pages(psm, bp, bw, x, y, w, h, pg, full);
    dl_why = "CPU read of a rectangle"; download_any(pg, n, 0);
}
/* 1 if the batch being gathered may draw on page p (its frame or Z buffer) */
static int batch_page(u32 p)
{
    if (!b_on) return 0;
    u32 rows = (u32)(bs.sy1 < 0 ? 0 : bs.sy1) + 1, w = bs.fbw ? bs.fbw : 1;
    u32 f0 = bs.fbp / 32, fn = ((rows + 31) / 32) * w + 1;           /* (16-bit pages hold 64 rows: this is more than enough) */
    if (((p - f0) & 511) < fn) return 1;
    if (bs.zte || !bs.zmsk) { u32 z0 = bs.zbp / 32; if (((p - z0) & 511) < fn) return 1; }
    return 0;
}
void gsgl_cpu_read(u32 bp, u32 nblocks)
{
    u16 pg[512]; int n = 0, any = 0;
    if (!nblocks) nblocks = 1;
    u32 p0 = bp / 32, p1 = (bp + nblocks - 1) / 32;
    if (p1 - p0 >= 512) p1 = p0 + 511;
    for (u32 p = p0; p <= p1; p++) { pg[n++] = (u16)(p & 511); if (owner[p & 511] >= 0 || batch_page(p & 511)) any = 1; }
    /* memory no GPU target has and the batch does not draw on: read as it is
     * (the CLUT loads of RAC1's menu: ending the batch for each cost a draw) */
    if (!any) return;
    if (!in_flush) gsgl_flush();
    { static char w[64]; snprintf(w, sizeof w, "CPU read from %p", __builtin_return_address(0)); dl_why = w; }
    download_any(pg, n, 0);
}
void gsgl_tex_read(u32 psm, u32 tbp, u32 tbw, u32 tw, u32 th)
{
    u16 pg[512]; u8 full[512];
    int n = tex_pages(psm, tbp, tbw, tw, th, pg, full), any = 0;
    u8 skip[512];
    for (int i = 0; i < n; i++) {
        int o = owner[pg[i]];
        /* (not UYA_GL_STRICT) a level read in another format than a target drew there: garbage the game never shows */
        skip[i] = o >= 0 && no_dl && (int)tg[o].cls != cls_of(psm);
        if (o >= 0 && !skip[i]) any = 1;
    }
    if (!any) return;
    if (!in_flush) gsgl_flush();
    dl_why = "texture decode"; download_any(pg, n, skip);
}
/* would gsgl_tex_read download pages of this level (a GPU target owns some, and they are
 * not skipped): then GS memory there is not what the level's decode will read */
int gsgl_tex_owned(u32 psm, u32 tbp, u32 tbw, u32 tw, u32 th)
{
    u16 pg[512]; u8 full[512];
    int n = tex_pages(psm, tbp, tbw, tw, th, pg, full);
    for (int i = 0; i < n; i++) {
        int o = owner[pg[i]];
        if (o >= 0 && !(no_dl && (int)tg[o].cls != cls_of(psm))) return 1;
    }
    return 0;
}
void gsgl_cpu_write_rect(u32 psm, u32 bp, u32 bw, u32 x, u32 y, u32 w, u32 h)
{
    if (!in_flush) gsgl_flush();
    u16 pg[512]; u8 full[512];
    int n = rect_pages(psm, bp, bw, x, y, w, h, pg, full);
    static char why[96]; snprintf(why, sizeof why, "CPU write psm %X bp %04X bw %u %u,%u %ux%u", psm, bp, bw, x, y, w, h); dl_why = why;
    download_any(pg, n, full);       /* pages the write only partly covers keep the rest */
    for (int i = 0; i < n; i++) {
        owner[pg[i]] = -1;
        for (int k = 0; k < NTG; k++) tg[k].valid[pg[i]] = 0;
    }
}

/* ---- batches ---- */
/* a vertex: Z as a base (the primitive's smallest Z, flat) plus a float offset,
 * so Z interpolates to the unit even near 2^24 and 2^32 */
typedef struct { float x, y, U, V, Q, dz; u32 zr; u8 r, g, b, a; u8 f, div, p0, p1; } gv_t;
static u32 zref;
static int cur_rec;                       /* the texture record of the primitives being added */
static int seg_v[4096], nseg;             /* where each run of one record's primitives starts (vertex index) */
static float seg_bb[4096][4];             /* each run's bounding box */
static pcmd_t rec_st[REC_MAX];           /* the states of records 1.. (record 0 is the batch's own) */
static gv_t *vb; static int nv, vcap;
static int b_mode; static u32 b_st;
static float bx0, by0, bx1, by1, bqmin, bqmax, bu0, bu1, bv0, bv1;
static int b_uvall;                       /* the texture coordinates can be anywhere (perspective through Q = 0) */
/* a batch of sprites only (clears, copies): their pixel rectangles, while they do not overlap */
#define NSPR 64
static int b_spr, b_nspr; static int b_sr[NSPR][4];

static inline void put(float x, float y, float U, float V, float Q, u32 z, const vtx_t *c, u8 f, u8 div)
{
    gv_t *o = &vb[nv++];
    if (bs.zpsm == 0x31) z &= 0xFFFFFF;   /* Z24 uses the low 24 bits */
    o->x = x; o->y = y; o->U = U; o->V = V; o->Q = Q; o->zr = zref; o->dz = (float)(z - zref);
    o->r = c->r; o->g = c->g; o->b = c->b; o->a = c->a; o->f = f; o->div = div; o->p0 = (u8)cur_rec; o->p1 = (u8)(cur_rec >> 8);
    if (x < bx0) bx0 = x;
    if (x > bx1) bx1 = x;
    if (y < by0) by0 = y;
    if (y > by1) by1 = y;
    float *sb = seg_bb[nseg - 1];
    if (x < sb[0]) sb[0] = x;
    if (x > sb[1]) sb[1] = x;
    if (y < sb[2]) sb[2] = y;
    if (y > sb[3]) sb[3] = y;
}
static inline void uvb(float u, float v)
{
    if (u < bu0) bu0 = u;
    if (u > bu1) bu1 = u;
    if (v < bv0) bv0 = v;
    if (v > bv1) bv1 = v;
}
static inline void qb(float q)
{
    if (q < bqmin) bqmin = q;
    if (q > bqmax) bqmax = q;
}

/* S differs from the batch's state only in its texture (and neither reads a
 * GPU target nor has levels decoded late) */
static int tex_only_change(const pcmd_t *S)
{
    if (!bs.tme || !S->tme || bs.rt || S->rt || nrec >= REC_MAX - 1 || b_mode != GL_TRIANGLES) {
        if (getenv("UYA_GLBRK")) { static unsigned long long c[8], tot; c[!bs.tme ? 0 : !S->tme ? 1 : bs.rt ? 2 : S->rt ? 3 : bs.defer ? 4 : S->defer ? 5 : 6]++;
            if (++tot % 20000 == 0) uya_log("merge refused: tme %llu/%llu rt %llu/%llu defer %llu/%llu other %llu", c[0], c[1], c[2], c[3], c[4], c[5], c[6]); }
        return 0;
    }
    if (getenv_cached_nomerge()) return 0;
    if (getenv("UYA_GL_NOMERGEDEF") && (S->defer || bs.defer)) return 0;
    pcmd_t t = *S;
    memcpy(t.lv, bs.lv, sizeof t.lv);
    t.tex0 = bs.tex0; t.tex1 = bs.tex1; t.miptbp1 = bs.miptbp1; t.miptbp2 = bs.miptbp2; t.clamp = bs.clamp; t.texa = bs.texa;
    t.tw = bs.tw; t.th = bs.th; t.k = bs.k; t.lcm = bs.lcm; t.mxl = bs.mxl; t.mmag = bs.mmag; t.mmin = bs.mmin; t.l = bs.l;
    t.wms = bs.wms; t.wmt = bs.wmt; t.minu = bs.minu; t.maxu = bs.maxu; t.minv = bs.minv; t.maxv = bs.maxv; t.tfx = bs.tfx; t.tcc = bs.tcc; t.defer = bs.defer;
    if (memcmp(&t, &bs, sizeof t)) {
        if (getenv("UYA_GLBRK")) {   /* testing: the first differing byte offset */
            static unsigned long long cnt[1024], tot; const u8 *a = (const u8 *)&t, *b = (const u8 *)&bs; size_t o = 0;
            while (o < sizeof t && a[o] == b[o]) o++;
            if (o < 1024) cnt[o]++;
            if (++tot % 20000 == 0) for (int i = 0; i < 1024; i++) if (cnt[i] > tot / 50) uya_log("merge refused at offset %d: %llu", i, cnt[i]);
        }
        return 0;
    }
    return 1;
}
void gsgl_prim(const pcmd_t *S, u32 sti, const pprim_t *pr)
{
    int mode = (pr->type == 3 || pr->type == 6) ? GL_TRIANGLES : GL_POINTS;
    if (b_on && sti != b_st && getenv("UYA_GLBRK")) {   /* testing: what changes between batches */
        static unsigned long long n[16], tot; const char *nm[16] = {"tex","blend","test","frame","scissor","wrap","fog","prim","mode","other"};
        int k = 9;
        if (memcmp(&bs.lv, &S->lv, sizeof bs.lv) || bs.tex0 != S->tex0) k = 0;
        else if (bs.abe != S->abe || bs.ba != S->ba || bs.bb != S->bb || bs.bc != S->bc || bs.bd != S->bd || bs.fix != S->fix) k = 1;
        else if (bs.ate != S->ate || bs.atst != S->atst || bs.aref != S->aref || bs.afail != S->afail || bs.zte != S->zte || bs.ztst != S->ztst || bs.zmsk != S->zmsk || bs.date != S->date) k = 2;
        else if (bs.fbp != S->fbp || bs.fbw != S->fbw || bs.zbp != S->zbp || bs.fbmsk != S->fbmsk) k = 3;
        else if (bs.sx0 != S->sx0 || bs.sx1 != S->sx1 || bs.sy0 != S->sy0 || bs.sy1 != S->sy1) k = 4;
        else if (bs.wms != S->wms || bs.wmt != S->wmt || bs.minu != S->minu || bs.maxu != S->maxu || bs.minv != S->minv || bs.maxv != S->maxv || bs.clamp != S->clamp) k = 5;
        else if (bs.fge != S->fge || bs.fogr != S->fogr) k = 6;
        else if (bs.tme != S->tme || bs.fst != S->fst || bs.iip != S->iip || bs.tfx != S->tfx || bs.tcc != S->tcc) k = 7;
        else if (bs.tex1 != S->tex1 || bs.mmag != S->mmag || bs.mmin != S->mmin || bs.texa != S->texa) k = 8;
        n[k]++; if (++tot % 40000 == 0) { char b[400]; int o = 0; for (int i = 0; i < 10; i++) o += snprintf(b + o, sizeof b - o, "%s %llu  ", nm[i], n[i]); uya_log("batch breaks: %s", b); }
    }
    if (b_on && sti != b_st && mode == b_mode && nv + 6 <= vcap && tex_only_change(S)) {
        /* the same but for the texture: a new texture record in the same batch */
        if (cur_rec == 0 || memcmp(&rec_st[cur_rec], S, sizeof *S)) {
            if (nrec == 0) nrec = 1;            /* (record 0: the batch's own state) */
            rec_st[nrec] = *S;
            rec_mxl[nrec] = S->mxl;
            if (S->defer) clut_snap(nrec);
            for (int l = 0; l < 7; l++) rec_tci[nrec][l] = S->lv[l].tci;
            pin_levels(S);
            cur_rec = nrec++;
        } 
        if (nseg < 4096) { seg_v[nseg] = nv; seg_bb[nseg][0] = seg_bb[nseg][2] = 1e30f; seg_bb[nseg][1] = seg_bb[nseg][3] = -1e30f; nseg++; }
        else { gsgl_flush(); }
        b_st = sti;
    }
    if (b_on && (sti != b_st || mode != b_mode || nv + 6 > vcap)) gsgl_flush();
    if (!b_on) {
        nrec = 0; cur_rec = 0; nseg = 1; seg_v[0] = 0; seg_bb[0][0] = seg_bb[0][2] = 1e30f; seg_bb[0][1] = seg_bb[0][3] = -1e30f;
        if (S->ztst == 0 || !S->fbw) return;           /* nothing passes the depth test */
        if (S->ate && S->atst == 0 && S->afail == 0) return;   /* nor the alpha test */
        if (!vb) { vcap = 1 << 16; vb = malloc(sizeof(gv_t) * (size_t)vcap); }
        bs = *S; b_st = sti; b_mode = mode; b_on = 1; nv = 0; b_uvall = 0; b_spr = 1; b_nspr = 0; b_clut_saved = 0;
        pin_levels(S);
        if (S->tme && S->defer && !S->rt) { clut_snap(0); b_clut_saved = 1; }
        bx0 = by0 = bu0 = bv0 = bqmin = 1e30f; bx1 = by1 = bu1 = bv1 = bqmax = -1e30f;
    }
    st.prims++;
    const vtx_t *v = pr->v;
    const int tme = bs.tme, fst = bs.fst;
    switch (pr->type) {
    case 3: {
        b_spr = 0;
        u32 m = bs.zpsm == 0x31 ? 0xFFFFFF : 0xFFFFFFFFu, z0 = v[0].z & m, z1 = v[1].z & m, z2 = v[2].z & m;
        zref = z0 < z1 ? z0 : z1; if (z2 < zref) zref = z2;
        for (int k = 0; k < 3; k++) {
            if (!tme) put(v[k].x, v[k].y, 0, 0, 1, v[k].z, &v[k], v[k].f, 0);
            else if (fst) { put(v[k].x, v[k].y, v[k].u, v[k].v, 1, v[k].z, &v[k], v[k].f, 0); uvb(v[k].u, v[k].v); }
            else {
                float U = v[k].s * S->tw, V = v[k].t * S->th, Q = v[k].q;
                put(v[k].x, v[k].y, U, V, Q, v[k].z, &v[k], v[k].f, 1);
                qb(Q);
                if (Q > 0) uvb(U / Q, V / Q); else b_uvall = 1;
            }
        }
        if (tme && !fst && ((bqmin <= 0) != (bqmax <= 0))) b_uvall = 1;
    } break;
    case 6: {
        const vtx_t *a = &v[0], *b = &v[1];
        if (b_spr) {
            int r[4] = { (int)ceilf(fminf(a->x, b->x)), (int)ceilf(fmaxf(a->x, b->x)) - 1, (int)ceilf(fminf(a->y, b->y)), (int)ceilf(fmaxf(a->y, b->y)) - 1 };
            if (b_nspr == NSPR) b_spr = 0;
            for (int i = 0; i < b_nspr && b_spr; i++)
                if (r[0] <= b_sr[i][1] && b_sr[i][0] <= r[1] && r[2] <= b_sr[i][3] && b_sr[i][2] <= r[3]) b_spr = 0;
            if (b_spr && r[1] >= r[0] && r[3] >= r[2]) { memcpy(b_sr[b_nspr], r, sizeof r); b_nspr++; }
        }
        float u0 = 0, v0 = 0, u1 = 0, v1 = 0, q = 1;
        if (tme) {
            if (fst) { u0 = a->u; v0 = a->v; u1 = b->u; v1 = b->v; }
            else {
                q = b->q;
                u0 = a->s * S->tw / q; v0 = a->t * S->th / q; u1 = b->s * S->tw / q; v1 = b->t * S->th / q;
                qb(q);
            }
            {   /* the texels the pixels' sample points reach (x from ceil(x0) to ceil(x1) - 1) */
                float xa = fminf(a->x, b->x), xb = fmaxf(a->x, b->x), ya = fminf(a->y, b->y), yb = fmaxf(a->y, b->y);
                float px0 = ceilf(xa), px1 = ceilf(xb) - 1, py0 = ceilf(ya), py1 = ceilf(yb) - 1;
                if (px1 >= px0 && py1 >= py0 && xb > xa && yb > ya) {
                    float ua = a->x <= b->x ? u0 : u1, ub = a->x <= b->x ? u1 : u0, va = a->y <= b->y ? v0 : v1, vb2 = a->y <= b->y ? v1 : v0;
                    float du = (ub - ua) / (xb - xa), dv = (vb2 - va) / (yb - ya);
                    uvb(ua + (px0 - xa) * du, va + (py0 - ya) * dv); uvb(ua + (px1 - xa) * du, va + (py1 - ya) * dv);
                } else { uvb(u0, v0); uvb(u1, v1); }
            }
        }
        float x0 = a->x, y0 = a->y, x1 = b->x, y1 = b->y;
        zref = bs.zpsm == 0x31 ? (b->z & 0xFFFFFF) : b->z;
        put(x0, y0, u0, v0, q, b->z, b, b->f, 0); put(x1, y0, u1, v0, q, b->z, b, b->f, 0); put(x0, y1, u0, v1, q, b->z, b, b->f, 0);
        put(x1, y0, u1, v0, q, b->z, b, b->f, 0); put(x1, y1, u1, v1, q, b->z, b, b->f, 0); put(x0, y1, u0, v1, q, b->z, b, b->f, 0);
    } break;
    case 1: {   /* lines: the pixels gs.c's r_line picks (a DDA rounding to the nearest pixel), as points */
        const vtx_t *a = &v[0], *b = &v[1];
        float ua = 0, va = 0, ub = 0, vb_ = 0, q = 1;
        if (tme) {
            if (fst) { ua = a->u; va = a->v; ub = b->u; vb_ = b->v; }
            else { ua = a->s * bs.tw / a->q; va = a->t * bs.th / a->q; ub = b->s * bs.tw / b->q; vb_ = b->t * bs.th / b->q; q = b->q; qb(q); }
            uvb(ua, va); uvb(ub, vb_);
        }
        float dx = b->x - a->x, dy = b->y - a->y;
        int n = (int)ceilf(fmaxf(fabsf(dx), fabsf(dy)));
        if (n <= 0) n = 1;
        if (n > 4096) n = 4096;
        zref = bs.zpsm == 0x31 ? (b->z & 0xFFFFFF) : b->z;
        for (int i = 0; i < n; i++) {
            if (nv + 1 > vcap) { gsgl_flush(); bs = *S; b_st = sti; b_mode = mode; b_on = 1; nv = 0; pin_levels(S); }
            float t = (float)i / n;
            vtx_t c = *a;
            c.r = (u8)(a->r + (b->r - a->r) * t); c.g = (u8)(a->g + (b->g - a->g) * t); c.b = (u8)(a->b + (b->b - a->b) * t); c.a = (u8)(a->a + (b->a - a->a) * t);
            put(floorf(a->x + dx * t + 0.5f), floorf(a->y + dy * t + 0.5f), ua + (ub - ua) * t, va + (vb_ - va) * t, q, b->z, &c, b->f, 0);
        }
    } break;
    default: {
        float u = 0, w = 0, q = 1;
        if (tme) {
            if (fst) { u = v[0].u; w = v[0].v; }
            else { q = v[0].q; u = v[0].s * bs.tw; w = v[0].t * bs.th; if (q != 0) { u /= q; w /= q; } qb(q); }
            uvb(u, w);
        }
        zref = bs.zpsm == 0x31 ? (v[0].z & 0xFFFFFF) : v[0].z;
        put(floorf(v[0].x), floorf(v[0].y), u, w, q, v[0].z, &v[0], v[0].f, 0);
    } break;
    }
}

/* the mip levels the batch's LOD range can use */
static void lod_levels(const pcmd_t *p, int *lmin, int *lmax)
{
    int mxl = p->mxl;
    *lmin = 0; *lmax = 0;
    if (p->mmin < 2 || mxl == 0) return;
    float lo, hi;
    if (p->lcm || p->fst || bqmax < bqmin) lo = hi = p->k;
    else {
        float a = fabsf(bqmin), b = fabsf(bqmax);
        float qa = (bqmin <= 0 && bqmax >= 0) ? 0 : (a < b ? a : b), qb_ = a > b ? a : b;
        float s = (float)(1 << p->l);
        lo = qb_ > 0 ? -log2f(qb_) * s + p->k : 1e9f;
        hi = qa > 0 ? -log2f(qa) * s + p->k : 1e9f;
    }
    lo -= 0.07f; hi += 0.07f;   /* the LOD's rounding to 1/16 and gs.c's log2 approximation */
    if (lo <= 0) *lmin = 0;
    else *lmin = (p->mmin == 3 || p->mmin == 5) ? (int)floorf(lo) : (int)floorf(lo + 0.5f);
    if (hi <= 0) *lmax = 0;
    else *lmax = (p->mmin == 3 || p->mmin == 5) ? (int)floorf(hi) + 1 : (int)floorf(hi + 0.5f);
    if (*lmin > mxl) *lmin = mxl;
    if (*lmax > mxl) *lmax = mxl;
    if (*lmin < 0) *lmin = 0;
}

static int lg_partial, lg_alias, lg_ad, lg_blend, lg_fmt, lg_clamp;
/* the blend: the source part S (shader, integers) and the destination's
 * factor (fixed function). (A - B) * C >> 7 + D = Cs * (a C' + d) + Cd * (a' C' + d'). */
static void blend_setup(const pcmd_t *p, int *bla, int *bld, int *neg, GLenum *eq, GLenum *df, float *bc)
{
    int A = p->ba, B = p->bb, D = p->bd;
    int a = (A == 0) - (B == 0), d = D == 0, a2 = (A == 1) - (B == 1), d2 = D == 1;
    if (A == B) { a = 0; a2 = 0; }
    if (p->bc == 1) logonce(&lg_ad, "blend C = destination alpha (taken as 1.0)");
    GLenum C = p->bc == 0 ? GL_SRC1_ALPHA : GL_CONSTANT_ALPHA, Cm = p->bc == 0 ? GL_ONE_MINUS_SRC1_ALPHA : GL_ONE_MINUS_CONSTANT_ALPHA;
    if (p->bc == 1) { C = GL_ONE; Cm = GL_ZERO; }
    *bc = p->bc == 2 ? (p->fix > 128 ? 1.0f : p->fix / 128.0f) : 1.0f;
    int dsign;
    if (a2 == 0 && d2 == 0) { *df = GL_ZERO; dsign = 1; }
    else if (a2 == 0) { *df = GL_ONE; dsign = 1; }
    else if (a2 == 1 && d2 == 0) { *df = C; dsign = 1; }
    else if (a2 == -1 && d2 == 0) { *df = C; dsign = -1; }
    else if (a2 == -1 && d2 == 1) { *df = Cm; dsign = 1; }
    else { *df = GL_ONE; dsign = 1; logonce(&lg_blend, "blend Cd * (1 + C) (taken as Cd)"); }
    int ssign = (a == -1 && d == 0) ? -1 : 1;
    *bla = a; *bld = d; *neg = ssign < 0;
    if (ssign > 0 && dsign > 0) *eq = GL_FUNC_ADD;
    else if (ssign > 0) *eq = GL_FUNC_SUBTRACT;
    else if (dsign > 0) *eq = GL_FUNC_REVERSE_SUBTRACT;
    else { *eq = GL_FUNC_ADD; *df = GL_ZERO; *bla = 0; *bld = 0; *neg = 0; }   /* <= 0: black */
}

static void copy_rect(GLuint src_tex, int which, int x0, int y0, int x1, int y1)
{
    if (!tmp_tex[which]) {
        tmp_tex[which] = mk_tex(GL_RGBA8, 2048 * sc, TGH * sc, GL_RGBA, GL_UNSIGNED_BYTE, 0);
        p_glGenFramebuffers(1, &tmp_fbo[which]);
        p_glBindFramebuffer(GL_FRAMEBUFFER, tmp_fbo[which]);
        p_glFramebufferTexture2D(GL_FRAMEBUFFER, GL_COLOR_ATTACHMENT0, GL_TEXTURE_2D, tmp_tex[which], 0);
        gc.fbo = ~0u;
        for (int u = 0; u < 9; u++) if (gc.tex[u] == tmp_tex[which]) gc.tex[u] = ~0u;
    }
    p_glBindFramebuffer(GL_READ_FRAMEBUFFER, rd_fbo);
    p_glFramebufferTexture2D(GL_READ_FRAMEBUFFER, GL_COLOR_ATTACHMENT0, GL_TEXTURE_2D, src_tex, 0);
    p_glBindFramebuffer(GL_DRAW_FRAMEBUFFER, tmp_fbo[which]);
    p_glDisable(GL_SCISSOR_TEST);
    p_glBlitFramebuffer(x0 * sc, y0 * sc, (x1 + 1) * sc, (y1 + 1) * sc, x0 * sc, y0 * sc, (x1 + 1) * sc, (y1 + 1) * sc, GL_COLOR_BUFFER_BIT, GL_NEAREST);
    gc.sc[0] = -1;   /* the next batch enables and sets the scissor again */
    p_glFramebufferTexture2D(GL_READ_FRAMEBUFFER, GL_COLOR_ATTACHMENT0, GL_TEXTURE_2D, 0, 0);
    p_glBindFramebuffer(GL_FRAMEBUFFER, 0);
    gc.fbo = ~0u;
    st.copies++;
}

void gsgl_flush(void)
{
    if (!b_on) return;
    if (getenv("UYA_GLBRK")) {   /* testing: who ends batches */
        static void *ra[64]; static unsigned long long rn[64], tot; void *r = __builtin_return_address(0); int i;
        for (i = 0; i < 64 && ra[i] && ra[i] != r; i++) ;
        if (i < 64) { ra[i] = r; rn[i]++; }
        if (++tot % 40000 == 0) for (i = 0; i < 64 && ra[i]; i++) uya_log("flush from %p: %llu", ra[i], rn[i]);
    }
    b_on = 0;
    if (!nv || in_flush) { nv = 0; return; }
    in_flush = 1;
    st.flushes++;
    if (strict < 0) { const char *e = getenv("UYA_GL_STRICT"); strict = e && atoi(e); }
    pcmd_t *p = &bs;
    int fc = cls_of(p->fpsm);
    if (fc < 0 || CLS_Z(fc)) { logonce(&lg_fmt, "a frame buffer format it cannot draw"); goto done; }
    tgt_t *ct = tgt_get(p->fbp, p->fbw, fc, 0, 0);
    int x0 = (int)floorf(bx0) - 1, y0 = (int)floorf(by0) - 1, x1 = (int)ceilf(bx1) + 1, y1 = (int)ceilf(by1) + 1;
    if (x0 < p->sx0) x0 = p->sx0;
    if (y0 < p->sy0) y0 = p->sy0;
    if (x1 > p->sx1) x1 = p->sx1;
    if (y1 > p->sy1) y1 = p->sy1;
    if (x0 < 0) x0 = 0;
    if (y0 < 0) y0 = 0;
    if (x1 > ct->w - 1) x1 = ct->w - 1;
    if (y1 > ct->rows * ct->ph - 1) y1 = ct->rows * ct->ph - 1;
    if (x0 > x1 || y0 > y1) goto done;
    tgt_t *zt = 0;
    int zwrite = p->zte && !p->zmsk;
    if (p->zte && (p->ztst != 1 || zwrite)) {
        int zc = cls_of(p->zpsm);
        if (zc >= 0) zt = tgt_get(p->zbp, p->fbw, zc, ct, 0);
        if (zt) {   /* Z in the frame's own pages (a clear of both): colour only */
            static u8 mark[512]; static u32 gen_[512], gen; gen++;
            int hit = 0;
            for (int r = y0 / ct->ph; r <= y1 / ct->ph; r++) for (int c = x0 / 64; c <= x1 / 64; c++) gen_[tpage(ct, c, r)] = gen;
            for (int r = y0 / zt->ph; r <= y1 / zt->ph && !hit; r++) for (int c = x0 / 64; c <= x1 / 64; c++) if (gen_[tpage(zt, c, r)] == gen) { hit = 1; break; }
            (void)mark;
            if (hit) {
                static int n; if (n++ < 5) uya_log("GL GS: Z buffer %04X over the frame buffer %04X (rows %d-%d): Z ignored", zt->bp, ct->bp, y0, y1);
                zt = 0;
            }
        }
    }
    /* the target's current contents (before anything reads them); not for
     * pages non-overlapping sprites overwrite whole whatever was there */
    static u8 cov_c[512], cov_z[512];
    int opaque = b_spr && b_nspr && b_mode == GL_TRIANGLES && (!p->ate || p->atst == 1) && !p->date;
    int cc = opaque && !p->abe && !p->fbmsk && (fc == TC32 ? p->fpsm == 0x00 : 1) && !(p->tme && p->rt && &tg[p->rt - 1] == ct);
    int cz = opaque && zt && zwrite && p->ztst == 1;
    if (cc || cz) {
        memset(cov_c, 0, sizeof cov_c); memset(cov_z, 0, sizeof cov_z);
        for (int k = 0; k < 2; k++) {
            tgt_t *t = k ? zt : ct; u8 *cv = k ? cov_z : cov_c;
            if (!(k ? cz : cc)) continue;
            for (int r = y0 / t->ph; r <= y1 / t->ph; r++)
                for (int c = x0 / 64; c <= x1 / 64; c++) {
                    int px0 = c * 64, px1 = px0 + 63, py0 = r * t->ph, py1 = py0 + t->ph - 1, area = 0;
                    if (px0 < p->sx0 || px1 > p->sx1 || py0 < p->sy0 || py1 > p->sy1) continue;   /* (the scissor cuts it) */
                    for (int i = 0; i < b_nspr; i++) {
                        int w = (b_sr[i][1] < px1 ? b_sr[i][1] : px1) - (b_sr[i][0] > px0 ? b_sr[i][0] : px0) + 1;
                        int h = (b_sr[i][3] < py1 ? b_sr[i][3] : py1) - (b_sr[i][2] > py0 ? b_sr[i][2] : py0) + 1;
                        if (w > 0 && h > 0) area += w * h;
                    }
                    if (area == 64 * t->ph) cv[tpage(t, c, r)] = 1;
                }
        }
    }
    cover = cc ? cov_c : 0;
    ensure_valid(ct, x0, y0, x1, y1);
    cover = cz ? cov_z : 0;
    if (zt) ensure_valid(zt, x0, y0, x1, y1);
    cover = 0;
    /* the texture */
    tgt_t *rt = 0; GLuint rtex = dummy_f;
    tlevel_t lv[7]; int lmin = 0, lmax = 0;
    memcpy(lv, p->lv, sizeof lv);
    if (p->tme && p->rt) {
        rt = &tg[p->rt - 1];
        if (!rt->used || rt->bp != BITS(p->tex0, 0, 14) || rt->bw != BITS(p->tex0, 14, 6) || rt->cls != TC32) {   /* gone: decode it */
            rt = 0; p->rt = 0; p->defer = 1;
        }
    }
    if (p->tme && rt) {
        int tw = (int)p->tw, th = (int)p->th, u0 = 0, u1 = tw - 1, v0 = 0, v1 = th - 1;
        if (!b_uvall && bu1 >= bu0) {
            int lin = p->mmag || p->mmin == 1 || p->mmin == 4 || p->mmin == 5;   /* bilinear reads x - 0.5 and the next */
            float h = lin ? 0.5f : 0.0f;
            int a = (int)floorf(bu0 - h), b = (int)floorf(bu1 - h) + lin, c = (int)floorf(bv0 - h), d = (int)floorf(bv1 - h) + lin;
            if (p->wms == 1) { a = a < 0 ? 0 : a; b = b > tw - 1 ? tw - 1 : b; }
            else if (p->wms == 2) { a = a < p->minu ? p->minu : a; b = b > p->maxu ? p->maxu : b; }
            if (p->wmt == 1) { c = c < 0 ? 0 : c; d = d > th - 1 ? th - 1 : d; }
            else if (p->wmt == 2) { c = c < p->minv ? p->minv : c; d = d > p->maxv ? p->maxv : d; }
            if ((p->wms == 0 && a >= 0 && b < tw) || p->wms == 1 || p->wms == 2) { u0 = a; u1 = b; }
            if ((p->wmt == 0 && c >= 0 && d < th) || p->wmt == 1 || p->wmt == 2) { v0 = c; v1 = d; }
        }
        no_dl = !strict;
        ensure_valid(rt, u0, v0, u1, v1);
        no_dl = 0;
        lv[0].lw = tw; lv[0].lh = th; lv[0].w = rt->w; lv[0].h = rt->rows * rt->ph;
        if (rt == ct) { copy_rect(ct->tex, 0, u0 < 0 ? 0 : u0, v0 < 0 ? 0 : v0, u1 >= ct->w ? ct->w - 1 : u1, v1 >= TGH ? TGH - 1 : v1); rtex = tmp_tex[0]; }
        else rtex = rt->tex;
    } else if (p->tme) {
        lod_levels(p, &lmin, &lmax);
        if (b_clut_saved) gs_clut_swap(rec_clut[0], &rec_cluth[0]);   /* the batch's palette */
        for (int l = 0; l <= p->mxl && l < 7; l++) {
            int need = l >= lmin && l <= lmax;
            if ((p->defer & (1 << l)) || tcser[lv[l].tci] != lv[l].ser) {
                if (!need) continue;
                no_dl = !strict;
                if (gs_tex_late(p, l, &lv[l])) { gsgl_tex_touch(&lv[l]); st.late++; }
                no_dl = 0;
            }
        }
        if (b_clut_saved) gs_clut_swap(rec_clut[0], &rec_cluth[0]);   /* back */
    }
    /* the destination alpha test reads the frame as it was before the batch */
    int date = p->date && ct->cls == TC32 && p->fpsm == 0x00;
    if (p->date && (ct->cls == TC16 || ct->cls == TC16S)) date = 1;
    if (date) copy_rect(ct->tex, 1, x0, y0, x1, y1);
    claim(ct, x0, y0, x1, y1);
    if (zt && zwrite) claim(zt, x0, y0, x1, y1);

    /* GL state */
    bind_fbo(fbo_get(ct->tex, zt ? zt->tex : 0));
    if (gc.vw != ct->w * sc || gc.vh != TGH * sc) { p_glViewport(0, 0, ct->w * sc, TGH * sc); gc.vw = ct->w * sc; gc.vh = TGH * sc; }
    if (gc.sc[0] != x0 || gc.sc[1] != y0 || gc.sc[2] != x1 || gc.sc[3] != y1) {
        p_glEnable(GL_SCISSOR_TEST);
        p_glScissor(x0 * sc, y0 * sc, (x1 - x0 + 1) * sc, (y1 - y0 + 1) * sc);
        gc.sc[0] = x0; gc.sc[1] = y0; gc.sc[2] = x1; gc.sc[3] = y1;
    }
    if (gc.prog != prog) { p_glUseProgram(prog); p_glBindVertexArray(vao); gc.prog = prog; }
    /* texture records: 0 is the batch's own state, 1.. the other textures merged in */
    if (nrec == 0) nrec = 1;
    u32 gen0 = atlas_gen;
    int place_tries = 0;
  records_again:
    for (int r = 0; r < nrec; r++) {
        const pcmd_t *q = r ? &rec_st[r] : p;
        tlevel_t rl[7];
        if (r) {
            memcpy(rl, q->lv, sizeof rl);
            int qmin = 0, qmax = 7;
            if (q->defer) { lod_levels(q, &qmin, &qmax); gs_clut_swap(rec_clut[r], &rec_cluth[r]); }
            for (int l = 0; l <= q->mxl && l < 7; l++) {
                if (q->defer & (1 << l)) {   /* decoded late: only the levels the batch's LOD range needs */
                    if (l < qmin || l > qmax) continue;
                    no_dl = !strict;
                    if (gs_tex_late(q, l, &rl[l])) { gsgl_tex_touch(&rl[l]); st.late++; }
                    no_dl = 0;
                } else if (!tc_ready(&rl[l])) { if (rl[l].px && tcser[rl[l].tci] != rl[l].ser) gs_tex_late(q, l, &rl[l]); gsgl_tex_touch(&rl[l]); }
            }
            if (q->defer) gs_clut_swap(rec_clut[r], &rec_cluth[r]);
            memcpy(rec_st[r].lv, rl, sizeof rl);   /* (decoded now: another pass of the loop finds them) */
            rec_st[r].defer = 0;
        } else {
            memcpy(rl, lv, sizeof rl);
            for (int l = 0; l <= q->mxl && l < 7; l++) if (q->tme && !rt && rl[l].px && !tc_ready(&rl[l])) gsgl_tex_touch(&rl[l]);
        }
        GLint *R = recs[r];
        memset(R, 0, sizeof recs[r]);
        R[0] = q->wms; R[1] = q->wmt; R[2] = q->minu; R[3] = q->maxu;
        R[4] = q->minv; R[5] = q->maxv; R[6] = q->mmag; R[7] = q->mmin;
        R[8] = q->mxl; R[9] = q->lcm; R[10] = q->l; { float k = q->k; memcpy(&R[11], &k, 4); }
        R[12] = q->tfx; R[13] = q->tcc;
        for (int l = 0; l < 7; l++) {
            GLint *L4 = R + 16 + l * 8;
            int ok = q->tme && (r || !rt) && l <= q->mxl && tc_ready(&rl[l]);
            int ci = rl[l].tci;
            L4[0] = ok ? tcax[ci] : 0; L4[1] = ok ? tcay[ci] : 0;
            L4[2] = rl[l].w > 0 ? rl[l].w : 1; L4[3] = rl[l].h > 0 ? rl[l].h : 1;
            if (!ok) { L4[2] = 1; L4[3] = 1; L4[0] = 0; L4[1] = 0; }
            if (r == 0 && rt && l == 0) { L4[2] = lv[0].w; L4[3] = lv[0].h; }
            L4[4] = rl[l].lw > 0 ? rl[l].lw : 1; L4[5] = rl[l].lh > 0 ? rl[l].lh : 1;
        }
    }
    /* the atlas started over meanwhile: places again (at most twice: a batch whose textures
     * do not fit in the atlas at all would otherwise start it over forever) */
    if (atlas_gen != gen0 && ++place_tries < 3) { gen0 = atlas_gen; goto records_again; }
    p_glBindBuffer(GL_TEXTURE_BUFFER, rec_buf);
    p_glBufferSubData(GL_TEXTURE_BUFFER, 0, (GLsizeiptr)(sizeof recs[0]) * nrec, recs);
    if (gc.tex[9] != rec_tex) { p_glActiveTexture(GL_TEXTURE0 + 9); p_glBindTexture(GL_TEXTURE_BUFFER, rec_tex); gc.tex[9] = rec_tex; }
    bind_unit(0, atlas_tex);
    bind_unit(7, rtex);
    bind_unit(8, date ? tmp_tex[1] : dummy_f);
    int bla = 0, bld = 1, neg = 0; GLenum eq = GL_FUNC_ADD, df = GL_ZERO; float bcol = 1;
    if (p->abe) blend_setup(p, &bla, &bld, &neg, &eq, &df, &bcol);
    if (!p->clampc) logonce(&lg_clamp, "COLCLAMP off (wrapping) not done");
    {
        int on = p->abe != 0;
        if (gc.blend != on) { if (on) p_glEnable(GL_BLEND); else p_glDisable(GL_BLEND); gc.blend = on; }
        if (on && (gc.eq != eq || gc.df != df)) {
            p_glBlendEquationSeparate(eq, GL_FUNC_ADD);
            p_glBlendFuncSeparate(GL_ONE, df, GL_ONE, GL_ZERO);
            gc.eq = eq; gc.df = df;
        }
        if (on && gc.bcol != bcol) { p_glBlendColor(0, 0, 0, bcol); gc.bcol = bcol; }
    }
    {
        int on = zt != 0;
        if (gc.depth != on) { if (on) p_glEnable(GL_DEPTH_TEST); else p_glDisable(GL_DEPTH_TEST); gc.depth = on; }
        GLenum f = p->ztst == 3 ? GL_GREATER : (p->ztst == 2 ? GL_GEQUAL : GL_ALWAYS);
        if (on && gc.dfunc != f) { p_glDepthFunc(f); gc.dfunc = f; }
    }
    /* colour write mask (FBMSK whole bytes; PSMCT24 keeps alpha) */
    int cm = 15;
    if (fc == TC32) {
        for (int k = 0; k < 4; k++) {
            u32 m = (p->fbmsk >> (k * 8)) & 255;
            if (m == 255) cm &= ~(1 << k);
            else if (m) logonce(&lg_partial, "FBMSK with partial bytes (taken as written)");
        }
        if (p->fpsm == 0x01) cm &= 7;
    } else if (p->fbmsk & 0xFFFF) {
        if ((p->fbmsk & 0x8000) == 0x8000) cm &= 7;
        if ((p->fbmsk & 0x7FFF) == 0x7FFF) cm &= 8;
        else if (p->fbmsk & 0x7FFF) logonce(&lg_partial, "16-bit FBMSK (taken as written)");
    }
    int zw = zt && zwrite;
    /* passes: the alpha test's failing pixels get the AFAIL writes */
    struct { int apass, cm, zw; } ps[2]; int np = 0;
    if (!p->ate || p->atst == 1) { ps[0].apass = 0; ps[0].cm = cm; ps[0].zw = zw; np = 1; }
    else {
        int fcm = cm, fzw = 0;
        switch (p->afail) {
        case 1: fcm = cm; fzw = 0; break;
        case 2: fcm = 0; fzw = zw; break;
        case 3: fcm = cm & 7; fzw = 0; break;
        }
        if (p->afail == 0) { ps[0].apass = 1; ps[0].cm = cm; ps[0].zw = zw; np = 1; }
        else if (p->atst == 0) { ps[0].apass = 0; ps[0].cm = fcm; ps[0].zw = fzw; np = 1; }
        else { ps[0].apass = 1; ps[0].cm = cm; ps[0].zw = zw; ps[1].apass = 2; ps[1].cm = fcm; ps[1].zw = fzw; np = 2; }
    }
    GLint U[4 * 10];
    {
        int lin_mxl = p->mxl;
        int zfmt = p->zpsm == 0x30 ? 1 : ((p->zpsm == 0x32 || p->zpsm == 0x3A) ? 2 : 0);
        GLint u[40] = {
            p->tme, p->tfx, p->tcc, p->fge,
            p->ate && p->atst != 1, p->atst, p->aref, 0,
            p->fba, date, p->datm, CLS_16(fc),
            p->wms, p->wmt, p->minu, p->maxu,
            p->minv, p->maxv, p->mmag, p->mmin,
            lin_mxl, p->lcm, p->l, rt ? 1 : 0,
            rt && BITS(p->tex0, 20, 6) == 1, (GLint)BITS(p->texa, 0, 8), (GLint)BITS(p->texa, 15, 1), p->iip || b_mode == GL_POINTS,
            p->fogr, p->fogg, p->fogb, zfmt,
            bla, bld, p->bc == 0 ? 0 : (p->bc == 2 ? 1 : 2), p->fix,
            p->abe, rt ? rt->w : 1, rt ? rt->rows * rt->ph : 1, neg };
        memcpy(U, u, sizeof u);
    }

    p_glUniform4f(u_vp, 2.0f / (float)ct->w, 2.0f / (float)TGH, 0.5f - 1.0f / 128.0f, (float)sc);   /* (w: the point size) */
    int first;
    {   /* the vertices into a ring buffer: written ahead of what the GPU reads, orphaned when it wraps */
        static size_t off;
        size_t n = sizeof(gv_t) * (size_t)nv, cap = (size_t)8 << 20;
        p_glBindBuffer(GL_ARRAY_BUFFER, vbo);
        GLbitfield fl = GL_MAP_WRITE_BIT | GL_MAP_UNSYNCHRONIZED_BIT;
        if (off + n > cap) { p_glBufferData(GL_ARRAY_BUFFER, (GLsizeiptr)cap, 0, GL_STREAM_DRAW); off = 0; }
        if (glt_q) { u64 *c = glt_cmd(GLT_VB, 1, n); c[0] = (u64)off; memcpy(c + 1, vb, n); (void)fl; }   /* the GL thread maps and copies */
        else {
            void *m = p_glMapBufferRange(GL_ARRAY_BUFFER, (GLintptr)off, (GLsizeiptr)n, fl);
            if (m) { memcpy(m, vb, n); p_glUnmapBuffer(GL_ARRAY_BUFFER); }
        }
        first = (int)(off / sizeof(gv_t));
        off += n;
    }
    /* two passes (the alpha test's failing pixels): each run of one texture's
     * primitives gets both before the next run, as the GS draws them in order */
    /* (runs that do not overlap the ones before them in a group go together:
     * tiles of 32 pixels, 64 x 64) */
    int split = np > 1 && nrec > 1, u_sent = 0;
    static u64 gt[64];
    for (int g = 0; g < (split ? nseg : 1);) {
        int v0 = split ? seg_v[g] : 0, e = g + 1;
        if (split) {
            memset(gt, 0, sizeof gt);
            for (; e <= nseg; e++) {
                const float *b = seg_bb[e - 1];
                if (b[1] < b[0]) continue;
                int tx0 = (int)b[0] >> 5, tx1 = (int)b[1] >> 5, ty0 = (int)b[2] >> 5, ty1 = (int)b[3] >> 5;
                if (tx0 < 0) tx0 = 0; if (ty0 < 0) ty0 = 0; if (tx1 > 63) tx1 = 63; if (ty1 > 63) ty1 = 63;
                u64 m = (tx1 >= tx0) ? ((tx1 - tx0 == 63) ? ~0ull : (((1ull << (tx1 - tx0 + 1)) - 1) << tx0)) : 0;
                int hit = 0;
                for (int y = ty0; y <= ty1; y++) if (gt[y] & m) hit = 1;
                if (hit && e - 1 > g) { e--; break; }  /* overlaps the group: it starts the next */
                for (int y = ty0; y <= ty1; y++) gt[y] |= m;
            }
            if (e > nseg) e = nseg;
            if (e <= g) e = g + 1;
        }
        int v1 = (split && e < nseg) ? seg_v[e] : nv;
        g = split ? e : 1;
        if (v1 <= v0) continue;
        for (int k = 0; k < np; k++) {
            if (!u_sent) { p_glUniform4iv(u_i, 10, U); u_sent = 1; }
            if (gc_apass != ps[k].apass) { p_glUniform1i(u_apass, ps[k].apass); gc_apass = ps[k].apass; }
            if (gc.cmask != ps[k].cm) { p_glColorMask(ps[k].cm & 1, (ps[k].cm >> 1) & 1, (ps[k].cm >> 2) & 1, (ps[k].cm >> 3) & 1); gc.cmask = ps[k].cm; }
            if (gc.dmask != ps[k].zw) { p_glDepthMask((GLboolean)ps[k].zw); gc.dmask = ps[k].zw; }
            p_glDrawArrays((GLenum)b_mode, first + v0, v1 - v0);
            st.draws++;
        }
    }
    {   /* testing: UYA_GLPIX=x,y,fbp(hex),from_vsync logs the batches that change that pixel of that target */
        static int on = -1; static int px_, py_; static unsigned fb_, from_; static u32 last; static float lastz;
        if (on < 0) { const char *e = getenv("UYA_GLPIX"); on = e && sscanf(e, "%d,%d,%x,%u", &px_, &py_, &fb_, &from_) == 4; }
        if (on && ct->bp == fb_ && uya_frame_count() >= from_ && px_ >= x0 && px_ <= x1 && py_ >= y0 && py_ <= y1) {
            u32 v = 0; float z = -1;
            p_glReadPixels(px_ * sc, py_ * sc, 1, 1, GL_RGBA, GL_UNSIGNED_BYTE, &v);
            if (zt) p_glReadPixels(px_ * sc, py_ * sc, 1, 1, GL_DEPTH_COMPONENT, GL_FLOAT, &z);
            uya_log("pix v%u %08X z %08X%s: n %d tme %u tex0 %llX abe %u ate %u/%u/%u/%u zt %u/%u (Z %s) passes %d v0 %.1f,%.1f z %08X", uya_frame_count(), v, (u32)(z * 16777216.0f), v != last || z != lastz ? " CHANGED" : "",
                    nv, p->tme, (unsigned long long)p->tex0, p->abe, p->ate, p->atst, p->aref, p->afail, p->zte, p->ztst, zt ? "on" : "off", np, vb[0].x, vb[0].y, vb[0].zr);
            last = v; lastz = z;
            for (int r = 0; r < nrec; r++) { const GLint *R = recs[r]; const pcmd_t *q = r ? &rec_st[r] : p;
                uya_log("   rec %d: tex0 %llX tw %g th %g wm %d/%d %d-%d %d-%d mmag %d mmin %d mxl %d lcm %d tfx %d tcc %d L0 %d,%d %dx%d (%dx%d) defer %d", r, (unsigned long long)q->tex0, q->tw, q->th,
                        R[0], R[1], R[2], R[3], R[4], R[5], R[6], R[7], R[8], R[9], R[12], R[13], R[16], R[17], R[18], R[19], R[20], R[21], q->defer); }
        }
    }
done:
    {   /* UYA_GLDEBUG: GL errors after batches */
        static int dbg = -1, left = 20;
        if (dbg < 0) dbg = getenv("UYA_GLDEBUG") != 0;
        if (dbg && left > 0) { GLenum e = p_glGetError(); if (e) { left--; uya_log("GL GS: error %X after a batch (fpsm %X tme %u abe %u ate %u date %u rt %u)", e, p->fpsm, p->tme, p->abe, p->ate, p->date, p->rt); } }
    }
    nv = 0;
    in_flush = 0;
    gsgl_batch_id++;                                    /* the batch's texture slots are free to go */
    if (glt_q) { glt_wr = glt_pend; glt_publish(); }   /* the batch to the GL thread now */
}

