enum { TC32, TC16, TC16S, TZ32, TZ24, TZ16, TZ16S };
static int cls_of(u32 psm)
{
    switch (psm) {
    case 0x00: case 0x01: return TC32;
    case 0x02: return TC16;
    case 0x0A: return TC16S;
    case 0x30: return TZ32;
    case 0x31: return TZ24;
    case 0x32: return TZ16;
    case 0x3A: return TZ16S;
    }
    return -1;
}
