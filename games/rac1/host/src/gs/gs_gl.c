/* gs_gl.c: the GS's drawing on the GPU (OpenGL 3.3 core), PCSX2-hardware-
 * renderer style but kept small.
 *
 * gs.c stays the front end: GIF, registers, GS local memory (vram), transfers,
 * CLUTs and the texture cache (textures decoded to RGBA). Here:
 *  - targets: GL textures standing for GS buffers, by (base, width, format
 *    class): RGBA8 for colour (PSMCT32/24/16/16S), DEPTH32F for Z (Z32/24/16).
 *    Pixel (x, y) of the buffer is the sc x sc texels from (x*sc, y*sc) (no flip):
 *    sc is the upscale (UYA_SCALE, 1 = native). Transfers between GS memory and
 *    a target take one texel of each block (down) or fill the block (up).
 *  - coherence by 8 KB page: owner[p] is the target whose copy of page p is
 *    newer than vram (drawn on the GPU), and each target has valid[p] (its copy
 *    is current). A draw makes its pages valid (uploading from vram, after
 *    downloading other owners) and then owns them; CPU reads download owned
 *    pages; CPU writes download partly written ones and invalidate all copies.
 *  - primitives are batched per GS state (gs.c's state ring index) and drawn
 *    with one shader that does the GS pixel pipeline: texture fetch with the
 *    GS's wrap modes, nearest/bilinear and mip selection in integers (the
 *    same arithmetic as gs.c's tsample), TFX/TCC, fog, alpha test (AFAIL by a
 *    second pass), destination alpha test (a copy of the target), Z as
 *    integer values in a float depth buffer, and the blend (A-B)*C>>7+D with
 *    the source part computed in the shader and the destination part by
 *    fixed-function blending.
 *  - textures: decoded levels from gs.c's cache (RGBA8UI, texelFetch), or a
 *    colour target read directly (render to texture, the frame as a texture;
 *    copied first when it is also the draw target). Levels whose memory a
 *    target owns are decoded only when a batch's LOD range needs them (RAC1
 *    points level 0 of distant mip chains at the frame buffer).
 *  - display: the target under DISPFB drawn into the window. */
